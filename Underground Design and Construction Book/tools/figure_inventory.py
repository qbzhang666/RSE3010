"""Build FIGURES.md: every figure in the book with its label, source and status.

Run from the book folder:  python tools/figure_inventory.py
Status: 'new' = figure file not yet tracked by git, 'existing' otherwise;
'TikZ' = drawn in the LaTeX source rather than loaded from figures/.
"""
import re
import subprocess
from pathlib import Path

BOOK = Path(__file__).resolve().parents[1]
FILES = sorted((BOOK / "chapters").glob("c*.tex")) + sorted((BOOK / "backmatter").glob("appendix-*.tex"))

tracked = set(subprocess.run(["git", "ls-files", "figures"], cwd=BOOK, capture_output=True,
                             text=True).stdout.split())
scripts = {}
for py in sorted((BOOK / "tools").rglob("*.py")):
    for stem in re.findall(r"""["'](ch\d\d|app[A-Z])/([\w-]+)["']""", py.read_text(encoding="utf-8")):
        scripts.setdefault("/".join(stem), py.relative_to(BOOK).as_posix())
    for d, stem in re.findall(r"""save\(\s*\w*,?\s*["'](ch\d\d|app[A-Z])["']\s*,\s*["']([\w-]+)["']""",
                              py.read_text(encoding="utf-8")):
        scripts.setdefault(f"{d}/{stem}", py.relative_to(BOOK).as_posix())

rows, counts = [], {}
for f in FILES:
    text = f.read_text(encoding="utf-8")
    title = re.search(r"\\chapter\{([^}]*)\}", text)
    chap = f.stem
    for env in re.findall(r"\\begin\{figure\*?\}(.*?)\\end\{figure\*?\}", text, re.S):
        label = re.search(r"\\label\{([^}]*)\}", env)
        data = re.search(r"\\datafigure(?:\[([^\]]*)\])?\{([^}]*)\}", env)
        inc = re.search(r"\\includegraphics(?:\[[^\]]*\])?\{([^}]*)\}", env)
        cap = re.search(r"\\caption\{(.*)", env, re.S)
        capt = re.sub(r"\s+", " ", cap.group(1)) if cap else ""
        capt = re.split(r"(?<=[a-z0-9\)])\.\s", capt)[0][:110]
        if data:
            stem = data.group(2)
            status = "new" if not any(t.startswith(f"figures/{stem}.") for t in tracked) else "existing"
            width = data.group(1) or "full"
            src = scripts.get(stem, "")
        elif inc:
            stem, status, width, src = inc.group(1), "image", "", ""
        else:
            stem, status, width, src = "(TikZ)", "TikZ", "", "LaTeX source"
        width = width.replace("\\textwidth", " tw")
        rows.append((chap, label.group(1) if label else "", stem, status, width, src, capt))
        counts[status] = counts.get(status, 0) + 1

out = ["# Figure inventory", "",
       f"Generated by `tools/figure_inventory.py`. {len(rows)} figures: "
       + ", ".join(f"{v} {k}" for k, v in sorted(counts.items())) + ".", "",
       "| File | Label | Figure | Status | Width | Script | Caption (first sentence) |",
       "|---|---|---|---|---|---|---|"]
for r in rows:
    out.append("| " + " | ".join(c.replace("|", "/") for c in r) + " |")
(BOOK / "FIGURES.md").write_text("\n".join(out) + "\n", encoding="utf-8")
print(len(rows), counts)
